#!/usr/bin/env python3
"""Regenerate data/pricing.js from the Hearingcare pricing-tool export.

Usage:
    python3 scripts/import_pricing.py path/to/CATALOGUE_AND_PAYMENT_DATA.json

Only Phonak entries are imported (the tool pitches Phonak upgrades). Each entry
keeps the pricing tool's own id, so data/new-specs.js can map specs to it.
Prices are copied as supplied; nothing is recalculated except the documented
single-aid fallback (pair x 0.699450507240, rounded to the nearest GBP 5).
"""
import json
import sys
from datetime import date
from pathlib import Path

SINGLE_FACTOR = 0.699450507240


def single_price(aid):
    if aid.get("pairOnly"):
        return None
    if aid.get("singlePrice"):
        return aid["singlePrice"]
    return round(aid["price"] * SINGLE_FACTOR / 5) * 5


def main(src):
    data = json.loads(Path(src).read_text(encoding="utf-8"))
    aids = data["aids"] if isinstance(data, dict) else data
    rows = []
    for aid in aids:
        if not aid.get("family", "").startswith("Phonak"):
            continue
        if not aid.get("price"):
            sys.exit(f"Missing pair price for {aid['id']}")
        rows.append({
            "id": aid["id"],
            "family": aid["family"],
            "name": aid["name"],
            "tier": aid["tier"].replace("Platinum +", "Platinum Plus"),
            "pairPrice": aid["price"],
            "singlePrice": single_price(aid),
            "singleIsSupplied": bool(aid.get("singlePrice")),
            "pairOnly": bool(aid.get("pairOnly")),
        })
    out = Path(__file__).resolve().parent.parent / "data" / "pricing.js"
    header = (
        "// GENERATED by scripts/import_pricing.py - do not edit by hand.\n"
        f"// Source: {Path(src).name}, imported {date.today().isoformat()}.\n"
    )
    body = json.dumps({"source": Path(src).name, "importedOn": date.today().isoformat(), "models": rows},
                      ensure_ascii=False, indent=2)
    out.write_text(header + "window.HC_PRICING = " + body + ";\n", encoding="utf-8")
    print(f"Wrote {len(rows)} Phonak models to {out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
